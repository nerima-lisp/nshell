#!/usr/bin/env python3
"""Generate the bundled third-party completion plist from checked-in JSON."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "scripts" / "completion-command-kb.json"
DEFAULT_OUTPUT = ROOT / "data" / "domain" / "completion" / "generated-external-command-kb-data.lisp"


def lisp_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def spec_form(spec: dict[str, Any]) -> str:
    parts = [lisp_string(spec["command"])]
    if spec.get("description"):
        parts.extend([":description", lisp_string(spec["description"])])
    for key in ("subcommands", "flags"):
        values = spec.get(key, [])
        if values:
            parts.extend([f":{key}", "(" + " ".join(lisp_string(value) for value in values) + ")"])
    return "(" + " ".join(parts) + ")"


def render(data: dict[str, Any]) -> str:
    if data.get("schema_version") != 1 or not isinstance(data.get("commands"), list):
        raise ValueError("unsupported completion KB source schema")
    commands = data["commands"]
    names = [entry.get("command") for entry in commands]
    if any(not isinstance(name, str) or not name for name in names):
        raise ValueError("every KB record needs a non-empty command")
    if len(names) != len(set(names)):
        raise ValueError("KB command records must be unique")
    forms = "\n".join("               " + spec_form(entry) for entry in commands)
    return (
        ";; Generated by scripts/generate-completion-kb.py from scripts/completion-command-kb.json.\n"
        "(in-package #:nshell.domain.completion)\n\n"
        "(setf +external-subcommand-completion-specs+\n"
        "      (append +external-subcommand-completion-specs+\n"
        "              '(\n"
        f"{forms})))\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    data = json.loads(args.source.read_text(encoding="utf-8"))
    rendered = render(data)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as output:
        output.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
